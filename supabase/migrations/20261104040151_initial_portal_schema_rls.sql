  id uuid primary key references auth.users(id) on delete cascade,
  role public.app_role not null default 'freelancer',
  full_name text not null default '',
  phone text,
  avatar_path text,
  locale text not null default 'en',
  is_active boolean not null default true,
  two_factor_enabled boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.organizations (
  id uuid primary key default gen_random_uuid(),
  type public.org_type not null,
  name text not null,
  billing_email text,
  vat_number text,
  country_code text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.organization_memberships (
  organization_id uuid not null references public.organizations(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  permission text not null default 'member' check (permission in ('owner', 'manager', 'member', 'viewer')),
  created_at timestamptz not null default now(),
  primary key (organization_id, user_id)
);

create table public.engineer_profiles (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  skills text[] not null default '{}',
  countries text[] not null default '{}',
  hourly_rate numeric(12,2) check (hourly_rate is null or hourly_rate >= 0),
  currency text not null default 'EUR' check (currency ~ '^[A-Z]{3}$'),
  availability text not null default 'offline' check (availability in ('offline', 'available', 'busy')),
  verification_status text not null default 'pending' check (verification_status in ('pending', 'approved', 'rejected', 'suspended')),
  rating numeric(3,2) check (rating is null or rating between 0 and 5),
  consent_location_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.sites (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete restrict,
  name text not null,
  address text not null,
  country_code text,
  latitude double precision check (latitude is null or latitude between -90 and 90),
  longitude double precision check (longitude is null or longitude between -180 and 180),
  geofence_radius_m integer not null default 150 check (geofence_radius_m between 25 and 2000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
