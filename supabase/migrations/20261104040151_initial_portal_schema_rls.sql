-- SECURITY DEFINER helpers avoid recursive RLS evaluation. These expose only boolean scope checks.
create or replace function public.current_app_role()
returns public.app_role language sql stable security definer set search_path = '' as $$
  select p.role from public.profiles p where p.id = (select auth.uid()) and p.is_active = true
$$;

create or replace function public.is_internal_user()
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce(public.current_app_role() in ('admin', 'staff'), false)
$$;

create or replace function public.is_org_member(target_org uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.organization_memberships m where m.organization_id = target_org and m.user_id = (select auth.uid()))
$$;

create or replace function public.can_access_ticket(target_ticket uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce(public.is_internal_user(), false) or exists (
    select 1 from public.tickets t
    where t.id = target_ticket and (
      public.is_org_member(t.client_org_id)
      or t.assigned_to = (select auth.uid())
      or exists (select 1 from public.ticket_offers o where o.ticket_id = t.id and o.engineer_id = (select auth.uid()) and o.status = 'accepted')
    )
  )
$$;

create or replace function public.can_access_site_instructions(target_site uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select public.is_internal_user() or exists (
    select 1 from public.tickets t where t.site_id = target_site and t.assigned_to = (select auth.uid())
      and t.status in ('assigned','en_route','on_site','in_progress','waiting_client','waiting_parts','completed_pending_approval','approved')
  )
$$;

-- Create a minimal profile at signup. Role remains freelancer by default; privileged role changes
-- must be performed only through trusted admin tooling/service role after verification.
create or replace function public.handle_new_auth_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''))
  on conflict (id) do nothing;
  return new;
end;
$$;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_auth_user();

-- Atomic first-accept-wins. Ticket row lock serializes concurrent acceptance attempts.
create or replace function public.accept_offer(target_offer uuid)
returns table (accepted boolean, result text)
language plpgsql security definer set search_path = '' as $$
declare
  offer_row public.ticket_offers%rowtype;
  ticket_row public.tickets%rowtype;
begin
  select * into offer_row from public.ticket_offers where id = target_offer for update;
  if not found or offer_row.engineer_id <> (select auth.uid()) then
    return query select false, 'not_found_or_not_owner'::text; return;
  end if;
  select * into ticket_row from public.tickets where id = offer_row.ticket_id for update;
  if offer_row.status <> 'pending' or offer_row.expires_at <= now() or ticket_row.status <> 'offered' then
    return query select false, 'offer_unavailable'::text; return;
  end if;
  update public.tickets set assigned_to = offer_row.engineer_id, status = 'assigned' where id = ticket_row.id;
  update public.ticket_offers set status = 'accepted', responded_at = now() where id = offer_row.id;
  update public.ticket_offers set status = 'taken', responded_at = now()
    where ticket_id = ticket_row.id and id <> offer_row.id and status = 'pending';
  insert into public.ticket_events(ticket_id, actor_id, event_type, payload)
    values (ticket_row.id, offer_row.engineer_id, 'offer.accepted', jsonb_build_object('offer_id', offer_row.id));
  return query select true, 'accepted'::text;
end;
$$;
revoke all on function public.accept_offer(uuid) from public;
grant execute on function public.accept_offer(uuid) to authenticated;

