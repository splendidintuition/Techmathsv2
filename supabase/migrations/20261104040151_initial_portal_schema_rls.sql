create table public.messages (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.tickets(id) on delete cascade,
  channel public.message_channel not null default 'client',
  sender_id uuid not null references public.profiles(id) on delete restrict,
  body text not null check (length(body) between 1 and 10000),
  attachment_paths text[] not null default '{}',
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create table public.time_entries (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.tickets(id) on delete restrict,
  engineer_id uuid not null references public.profiles(id) on delete restrict,
  category public.time_category not null,
  started_at timestamptz not null,
  ended_at timestamptz,
  minutes integer generated always as (
    case when ended_at is null then null else greatest(0, floor(extract(epoch from (ended_at - started_at)) / 60)::integer) end
  ) stored,
  source public.time_source not null default 'timer',
  approval_status public.approval_status not null default 'draft',
  notes text,
  approved_by uuid references public.profiles(id) on delete set null,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ended_at is null or ended_at >= started_at)
);

